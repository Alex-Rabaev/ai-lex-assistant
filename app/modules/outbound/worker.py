"""RabbitMQ worker for processing outbound messages."""

import logging
import json
import signal
import asyncio
from typing import Optional

from app.common.messaging.connection import RabbitMQConnection
from app.modules.connections.repository import ConnectionRepository
from app.modules.connections.models import ConnectionChannel, Connection
from app.modules.conversations.service import ConversationsService
from app.modules.connections.vendors.webchat.publisher import WebsocketPublisher
from app.modules.outbound.schemas import OutgoingMessage, SendResult
from app.modules.outbound.vendors.telegram.sender import TelegramSender
from app.modules.outbound.vendors.whatsapp.sender import WhatsAppSender
from app.modules.outbound.vendors.webchat.sender import WebchatSender
from app.modules.outbound.exceptions import (
    UserBlockedError,
    InvalidTokenError,
    TemporaryError,
)
from app.common.utils.logging_context import set_log_context, clear_log_context

logger = logging.getLogger(__name__)


class OutboundWorker:
    """
    Worker for processing outbound messages from RabbitMQ queue.
    
    Consumes messages from the 'outbound_messages' queue (generated by
    conversations module), retrieves bot credentials, and sends responses
    to users via appropriate communication channels.
    """
    
    def __init__(self):
        """Initialize outbound worker."""
        self.rabbitmq_connection: Optional[RabbitMQConnection] = None
        self.connection_repo: Optional[ConnectionRepository] = None
        self._conversations_service: Optional[ConversationsService] = None
        self._websocket_publisher: Optional[WebsocketPublisher] = None
        self.running = False
        self._shutdown_event = asyncio.Event()
    
    async def start(self):
        """
        Start the worker and begin processing messages.
        """
        logger.info("🚀 Starting Outbound Worker...")
        
        signal.signal(signal.SIGTERM, self._signal_handler)
        signal.signal(signal.SIGINT, self._signal_handler)
        
        try:
            self.connection_repo = ConnectionRepository()
            self._conversations_service = ConversationsService()
            self._websocket_publisher = WebsocketPublisher()
            logger.info("✅ Connection repository initialized")
            
            self.rabbitmq_connection = RabbitMQConnection()
            await self.rabbitmq_connection.connect()
            
            queue = await self.rabbitmq_connection.declare_queue(
                "outbound_messages",
                durable=True
            )
            
            channel = await self.rabbitmq_connection.get_channel()
            await channel.set_qos(prefetch_count=1)
            
            logger.info("✅ Worker connected to RabbitMQ, waiting for messages...")
            self.running = True
            
            async with queue.iterator() as queue_iter:
                async for message in queue_iter:
                    if not self.running:
                        logger.info("Worker shutting down, stopping message consumption")
                        break
                    
                    async with message.process(ignore_processed=True):
                        try:
                            body = json.loads(message.body.decode())
                            outgoing_msg = OutgoingMessage(**body)
                            
                            set_log_context(
                                trace_id=outgoing_msg.trace_id,
                                assistant_id=outgoing_msg.assistant_id,
                                user_id=outgoing_msg.user_id
                            )
                            
                            logger.info(f"📨 Received outgoing message: type={outgoing_msg.type}")
                            
                            await self.process_message(outgoing_msg)
                            await message.ack()
                            
                        except Exception as e:
                            logger.error(f"❌ Error processing message: {e}", exc_info=True)
                            await message.nack(requeue=True)
                        
                        finally:
                            clear_log_context()
            
        except Exception as e:
            logger.error(f"Fatal error in worker: {e}", exc_info=True)
            raise
        finally:
            await self.shutdown()
    
    async def process_message(self, msg: OutgoingMessage):
        """
        Process a single message from the queue.
        
        Unified flow for all channels:
        1. Get connection from MongoDB
        2. Get appropriate sender for the channel
        3. Send message (typing or regular)
        4. Handle errors and update connection status
        """
        # Get connection
        connection = await self.connection_repo.get_by_id(msg.connection_id)
        
        if not connection:
            logger.error(f"❌ Connection not found: connection_id={msg.connection_id}")
            return
        
        # Get sender for this channel
        try:
            sender = self._get_sender(connection)
        except ValueError as e:
            logger.error(f"❌ Failed to initialize sender: {e}", exc_info=True)
            await connection.set_error_status(f"Failed to initialize sender: {e}", self.connection_repo)
            return
        
        if sender is None:
            logger.error(f"Unsupported channel: {connection.channel}")
            return
        
        # Send message
        await self._send(msg, sender, connection)
    
    def _get_sender(self, connection: Connection):
        """
        Get the appropriate sender for the connection channel.
        
        Args:
            connection: Connection object
            
        Returns:
            Sender instance or None if channel not supported
            
        Raises:
            ValueError: If sender initialization fails (e.g., bad token)
        """
        if connection.channel == ConnectionChannel.TELEGRAM:
            return TelegramSender(
                connection=connection,
                connection_repo=self.connection_repo
            )
        
        if connection.channel == ConnectionChannel.WHATSAPP:
            return WhatsAppSender(
                connection=connection,
                connection_repo=self.connection_repo
            )
        
        if connection.channel == ConnectionChannel.WEBCHAT:
            return WebchatSender(websocket_publisher=self._websocket_publisher)
        
        return None
    
    async def _send(self, msg: OutgoingMessage, sender, connection: Connection):
        """
        Send message using the provided sender.
        
        Unified send method for all channels - no channel-specific logic here.
        Each sender handles its own specifics internally.
        """
        is_external_channel = connection.channel in (ConnectionChannel.TELEGRAM, ConnectionChannel.WHATSAPP)
        
        # Handle typing indicator
        if msg.type == "typing_indicator":
            result = await sender.send_typing_indicator(
                user_id=msg.user_id,
                assistant_id=msg.assistant_id
            )
            
            if result.success:
                logger.info(f"✅ Typing indicator sent to user={msg.user_id}")
            else:
                logger.warning(f"⚠️ Failed to send typing indicator: {result.error}")
            return
        
        # Send message - unified call for all channels
        try:
            result = await sender.send_message(
                user_id=msg.user_id,
                text=msg.response_text,
                assistant_id=msg.assistant_id,
                conversation_id=msg.conversation_id,
                parse_mode=msg.parse_mode
            )
            
            if result.success:
                logger.info(
                    f"✅ Message sent: message_id={result.message_id}, user={msg.user_id}"
                )
                if is_external_channel:
                    await connection.set_connected(self.connection_repo)
                    await self._clear_blocked_if_needed(msg.user_id)
            else:
                logger.error(
                    f"❌ Failed to send message: error={result.error}, user={msg.user_id}"
                )
                
        except UserBlockedError:
            logger.warning(f"User {msg.user_id} has blocked the bot")
            if is_external_channel:
                await connection.set_degraded("User blocked the bot", self.connection_repo)
            await self._set_interlocutor_blocked(msg.user_id)
            
        except InvalidTokenError:
            logger.error(f"Invalid bot token for connection {connection.id}")
            if is_external_channel:
                await connection.set_error_status("Invalid bot token", self.connection_repo)
            
        except TemporaryError as e:
            logger.warning(f"Temporary error, message will be retried: {e}")
            raise  # Re-raise to trigger NACK and requeue
        
        except Exception as e:
            logger.error(f"Error sending message: {e}", exc_info=True)
            raise  # Re-raise to trigger NACK and requeue
    
    async def _set_interlocutor_blocked(self, user_id: str) -> None:
        try:
            interlocutor = await self._conversations_service.get_interlocutor_by_user_id(user_id)
            if interlocutor and not interlocutor.blocked:
                await self._conversations_service.update_interlocutor_blocked(str(interlocutor.id), blocked=True)
                logger.info(f"Marked interlocutor blocked: user_id={user_id}")
        except Exception as e:
            logger.error(f"Failed to mark interlocutor blocked: {e}")

    async def _clear_blocked_if_needed(self, user_id: str) -> None:
        try:
            interlocutor = await self._conversations_service.get_interlocutor_by_user_id(user_id)
            if interlocutor and interlocutor.blocked:
                await self._conversations_service.update_interlocutor_blocked(str(interlocutor.id), blocked=False)
                logger.info(f"Cleared interlocutor blocked: user_id={user_id}")
        except Exception as e:
            logger.error(f"Failed to clear interlocutor blocked: {e}")

    def _signal_handler(self, signum, frame):
        """Handle shutdown signals."""
        logger.info(f"Received signal {signum}, initiating graceful shutdown...")
        self.running = False
        self._shutdown_event.set()
    
    async def shutdown(self):
        """Perform graceful shutdown of the worker."""
        logger.info("🛑 Shutting down Outbound Worker...")
        self.running = False
        
        if self._websocket_publisher and self._websocket_publisher.connection.is_connected:
            try:
                await self._websocket_publisher.connection.close()
                logger.info("WebSocket publisher connection closed")
            except Exception as e:
                logger.error(f"Error closing WebSocket publisher connection: {e}")
        
        if self.rabbitmq_connection:
            try:
                await self.rabbitmq_connection.close()
                logger.info("RabbitMQ connection closed")
            except Exception as e:
                logger.error(f"Error closing RabbitMQ connection: {e}")
        
        logger.info("✅ Outbound Worker stopped")


async def main():
    """Main entry point for running the worker."""
    worker = OutboundWorker()
    await worker.start()


if __name__ == "__main__":
    from app.common.utils import setup_structured_logging
    setup_structured_logging()
    
    asyncio.run(main())
